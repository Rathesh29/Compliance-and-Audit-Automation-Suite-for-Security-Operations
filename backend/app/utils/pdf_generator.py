import io
from datetime import datetime, timezone
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch

def generate_pdf_report(
    title: str,
    site_name: str,
    date_range_start: str,
    date_range_end: str,
    compliance_score: float,
    generated_by: str,
    report_type: str,
    report_data: dict
) -> bytes:
    """Generate a clean enterprise PDF compliance & audit report."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()
    
    header_style = ParagraphStyle(
        'HeaderTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#0B132B')
    )
    
    subtitle_style = ParagraphStyle(
        'SubHeader',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        textColor=colors.HexColor('#4A5568')
    )

    section_style = ParagraphStyle(
        'SectionTitle',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=13,
        leading=16,
        textColor=colors.HexColor('#1E3A8A'),
        spaceBefore=10,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        'BodyDark',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#1F2937')
    )

    elements = []

    # Title Banner
    elements.append(Paragraph("SECURITY OPERATIONS AUDIT & COMPLIANCE SUITE", subtitle_style))
    elements.append(Paragraph(f"Official Audit Report: {title.upper()}", header_style))
    elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#1E3A8A'), spaceBefore=6, spaceAfter=12))

    # Metadata Grid
    meta_data = [
        [
            Paragraph(f"<b>Site:</b> {site_name}", body_style),
            Paragraph(f"<b>Report Type:</b> {report_type}", body_style)
        ],
        [
            Paragraph(f"<b>Period:</b> {date_range_start} to {date_range_end}", body_style),
            Paragraph(f"<b>Generated By:</b> {generated_by}", body_style)
        ],
        [
            Paragraph(f"<b>Generated At:</b> {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}", body_style),
            Paragraph(f"<b>Compliance Score:</b> <font color='{'#10B981' if compliance_score >= 80 else '#EF4444'}'><b>{compliance_score:.1f}%</b></font>", body_style)
        ]
    ]
    meta_table = Table(meta_data, colWidths=[270, 270])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F8FAFC')),
        ('PADDING', (0,0), (-1,-1), 6),
        ('BOX', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
        ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#E2E8F0')),
    ]))
    elements.append(meta_table)
    elements.append(Spacer(1, 14))

    # Attendance & Assignment Summary
    elements.append(Paragraph("1. Operational Attendance Summary", section_style))
    att_summary = report_data.get("attendance_summary", {})
    summary_data = [
        ["Metric", "Value", "Metric", "Value"],
        ["Total Scheduled Guards", str(att_summary.get("total_scheduled", 0)), "Valid Checked-in", str(att_summary.get("checked_in", 0))],
        ["Completed Shifts", str(att_summary.get("completed", 0)), "Missed Shifts", str(att_summary.get("missed", 0))],
        ["Late Check-ins", str(att_summary.get("late", 0)), "GPS Radius Breaches", str(att_summary.get("gps_violations", 0))]
    ]
    summary_table = Table(summary_data, colWidths=[150, 120, 150, 120])
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#1E293B')),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 8),
        ('BOTTOMPADDING', (0,0), (-1,-1), 4),
        ('TOPPADDING', (0,0), (-1,-1), 4),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
        ('BACKGROUND', (0,1), (-1,-1), colors.HexColor('#FFFFFF')),
    ]))
    elements.append(summary_table)
    elements.append(Spacer(1, 14))

    # Violations & Compliance Exceptions
    elements.append(Paragraph("2. Detected Compliance Exceptions", section_style))
    exceptions_list = report_data.get("exceptions", [])
    if exceptions_list:
        exc_rows = [["ID", "Violation Type", "Severity", "Detected At", "Status", "Resolution"]]
        for exc in exceptions_list[:15]: # Show up to 15 entries in report
            exc_rows.append([
                str(exc.get("id", "-")),
                str(exc.get("violation_type", "-")),
                str(exc.get("severity", "-")),
                str(exc.get("detected_at", "-")[:16] if exc.get("detected_at") else "-"),
                str(exc.get("status", "-")),
                str(exc.get("resolution_notes", "Pending") or "Pending")[:25]
            ])
        exc_table = Table(exc_rows, colWidths=[35, 120, 65, 100, 60, 160])
        exc_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#DC2626')),
            ('TEXTCOLOR', (0,0), (-1,0), colors.white),
            ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
            ('FONTSIZE', (0,0), (-1,-1), 7.5),
            ('BOTTOMPADDING', (0,0), (-1,-1), 3),
            ('TOPPADDING', (0,0), (-1,-1), 3),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
            ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor('#FEF2F2')]),
        ]))
        elements.append(exc_table)
    else:
        elements.append(Paragraph("<i>No compliance exceptions detected during this period. Full compliance maintained.</i>", body_style))
    
    elements.append(Spacer(1, 14))

    # Audit Trail Summary
    elements.append(Paragraph("3. Cryptographic Audit Chain Summary", section_style))
    audit_summary = report_data.get("audit_summary", {})
    integrity_status = "VERIFIED (Tamper-evident hash chain intact)" if audit_summary.get("chain_valid", True) else "TAMPER WARNING DETECTED"
    audit_rows = [
        ["Total Audit Events Logged", str(audit_summary.get("total_events", 0))],
        ["Cryptographic Integrity", integrity_status],
        ["Genesis Root Status", "Anchored (SHA-256)"],
        ["Last Record Hash", str(audit_summary.get("latest_hash", "GENESIS-CHAIN-ANCHORED"))[:48] + "..."]
    ]
    audit_table = Table(audit_rows, colWidths=[200, 340])
    audit_table.setStyle(TableStyle([
        ('FONTNAME', (0,0), (0,-1), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 8),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F8FAFC')),
        ('PADDING', (0,0), (-1,-1), 5),
    ]))
    elements.append(audit_table)

    # Footer note
    elements.append(Spacer(1, 20))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#94A3B8'), spaceBefore=6, spaceAfter=8))
    elements.append(Paragraph(
        "Confidential document generated by Compliance and Audit Automation Suite for Security Operations. "
        "All logs are immutable and cryptographically chained.",
        subtitle_style
    ))

    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
